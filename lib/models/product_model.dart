class Product {
  final String id;
  final String image;
  final String title;
  final double price;
  final double rating;
  final int reviewCount;
  final String description;
  final String category;

  Product({
    required this.id,
    required this.image,
    required this.title,
    required this.price,
    required this.rating,
    required this.reviewCount,
    required this.description,
    required this.category,
  });
}
